import XCTest
@testable import TianXianFruit

final class BusinessBillV3WireTests: XCTestCase {
    private func uuid(_ n: Int) -> String { String(format: "00000000-0000-0000-0000-%012d", n) }
    private let date = "2026-11-26"
    private let header = "微信订单号,交易时间,交易类型,收/支,金额,交易状态"
    private let row = "2026112600000000000000001,2026-11-26 17:01:00,经营收款,收入,13.25,成功"
    private func fixture(extra: String = "") throws -> (TXBillLocalPlan, TXBusinessV2EditorScope, Account, CloudBook, [SyncEvent]) {
        let scope = TXBusinessV2EditorScope(account:"seller", book:uuid(1), date:date, storeID:uuid(3), storeName:"A")
        let account = Account(username:"seller",displayName:"seller",systemRole:nil)
        let book = CloudBook(id:scope.book,name:"iOS_TEST_V39",role:"OWNER",deleted:nil,purged:nil)
        var draft = TXBusinessV2LocalDraft()
        draft.operationID = uuid(2); draft.end = "00:30"; draft.expense = "1"; draft.payer = uuid(5)
        draft.opening = "0"; draft.closing = "0"
        draft.collectors[0].partner = uuid(4)
        draft.collectors[0].wechat.natural = "10"
        draft.collectors[0].alipay.natural = "2.50"
        draft.collectors[0].cash.natural = "2.25"
        draft.collectors[0].replaceFollowing = true
        draft.collectors[0].wechat.morning = "2"
        draft.collectors[0].alipay.morning = "0"
        draft.collectors[0].cash.morning = "0"
        draft.collectors[0].acknowledge(previous:0,following:0)
        let batch = try TXBillBatchPreview([TXBillCSV.parse(fileName:"微信.csv",data:Data((header+"\n"+row+extra).utf8))])
        let plan = try TXBillLocalPlan.build(scope:scope,draft:draft,partner:uuid(4),batch:batch,
            confirmed:[.wechat],events:[],customerCursor:0)
        let records = [
            SyncEvent(tableName:"store",syncId:uuid(3),rowVersion:1,operation:"UPSERT",payload:["name":.string("A")]),
            SyncEvent(tableName:"partner",syncId:uuid(4),rowVersion:1,operation:"UPSERT",payload:["name":.string("收款人"),"id":.number(42)]),
            SyncEvent(tableName:"partner",syncId:uuid(5),rowVersion:1,operation:"UPSERT",payload:["name":.string("付款人"),"id":.exactInteger(9007199254740993)])]
        return (plan,scope,account,book,records)
    }
    func testExactPythonV39CanonicalAndScope() throws {
        let (plan,scope,account,book,records) = try fixture()
        let wire = try XCTUnwrap(plan.wireBill)
        XCTAssertEqual(wire.files.first?.file_hash, "7f433c84060026ace97721fc97e60101235f10a90ba26a16119572fd239d6802")
        let prepared = try TXBillV3Prepared.prepare(plan:plan,scope:scope,account:account,book:book,
            records:records,events:[],cursor:0)
        // Generated by actual Python V1.0.39 BusinessCommitV3Request and canonical_hash.
        XCTAssertEqual(prepared.hash, "ab4e74c72fdb3918859f915715a877973159ff8297ae5391b245e3e04b3a0646")
        XCTAssertNoThrow(try prepared.validate())
        XCTAssertEqual(prepared.base.prepared.proposal.totalRevenue,"20.00")
        XCTAssertEqual(wire.eventKeys.count,4)
        let roundtrip = try JSONDecoder().decode(TXBillV3Prepared.self,from:JSONEncoder().encode(prepared))
        XCTAssertEqual(roundtrip,prepared)
        XCTAssertThrowsError(try TXBillV3Prepared.prepare(plan:plan,scope:scope,account:account,book:book,
            records:records,events:[],cursor:1))
        let formal = CloudBook(id:book.id,name:"正式账本",role:"OWNER",deleted:nil,purged:nil)
        XCTAssertThrowsError(try TXBillV3Prepared.prepare(plan:plan,scope:scope,account:account,book:formal,
            records:records,events:[],cursor:0))
    }
    func testMultiDayFileNeverBecomesPartialV3Batch() throws {
        let (plan,scope,account,book,records) = try fixture(extra:"\n2026112700000000000000002,2026-11-27 00:01:00,经营收款,收入,2,成功")
        XCTAssertNil(plan.wireBill)
        XCTAssertEqual(plan.proposed.collectors[0].wechat.natural,"13.25")
        XCTAssertThrowsError(try TXBillV3Prepared.prepare(plan:plan,scope:scope,account:account,book:book,
            records:records,events:[],cursor:0))
    }
    func testV3CapabilitiesFailClosed() throws {
        let (_,_,_,book,_) = try fixture()
        let text = """
        {"version":3,"feature":"business_bill_atomic_v3","scope":"test","enabled":true,"atomic":true,"idempotency":true,"new_sale_only":true,"max_receipts":1000}
        """
        let caps = try JSONDecoder().decode(TXBillV3Capabilities.self,from:Data(text.utf8))
        XCTAssertTrue(caps.allows(book:book))
        XCTAssertFalse(caps.allows(book:CloudBook(id:book.id,name:"正式账本",role:"OWNER",deleted:nil,purged:nil)))
        let disabled = try JSONDecoder().decode(TXBillV3Capabilities.self,from:Data(text.replacingOccurrences(of:"\"enabled\":true",with:"\"enabled\":false").utf8))
        XCTAssertFalse(disabled.allows(book:book))
    }

    func testImmutableBodyAndOutboxReopen() throws {
        let (plan,scope,account,book,records) = try fixture()
        let request = try TXBillV3Prepared.prepare(plan:plan,scope:scope,account:account,book:book,
            records:records,events:[],cursor:0)
        let body = try XCTUnwrap(JSONSerialization.jsonObject(with: request.body(deviceID: "test-device")) as? [String:Any])
        XCTAssertEqual(body["protocol_version"] as? Int,3)
        XCTAssertEqual(body["device_id"] as? String,"test-device")
        XCTAssertEqual(body["payload_hash"] as? String,request.hash)
        var withoutTransport = body
        withoutTransport.removeValue(forKey:"device_id")
        withoutTransport.removeValue(forKey:"payload_hash")
        XCTAssertEqual(try JSONSerialization.data(withJSONObject:withoutTransport,options:[.sortedKeys,.withoutEscapingSlashes]),request.canonical)
        let folder = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at:folder) }
        let file = folder.appendingPathComponent("v3.sqlite")
        let outbox = try TXBillV3Outbox(url:file)
        XCTAssertNil(try outbox.load(scope))
        try outbox.reserve(request)
        XCTAssertThrowsError(try outbox.reserve(request))
        XCTAssertEqual(try TXBillV3Outbox(url:file).load(scope),request)
        let other = TXBusinessV2EditorScope(account:"other",book:scope.book,date:scope.date,storeID:scope.storeID,storeName:scope.storeName)
        XCTAssertNil(try outbox.load(other))
        let invalid = TXBillV3Prepared(base:request.base,bill:request.bill,canonical:request.canonical,hash:String(repeating:"0",count:64))
        XCTAssertThrowsError(try outbox.reserve(invalid))
        XCTAssertEqual(try outbox.load(scope),request)
    }

    func testReceiptRejectsWrongHashMissingEventAndStaleCursor() throws {
        let (plan,scope,account,book,records) = try fixture()
        let request = try TXBillV3Prepared.prepare(plan:plan,scope:scope,account:account,book:book,
            records:records,events:[],cursor:0)
        let wire = try request.base.validated()
        let revisions: [[String:Any]] = wire.natural.map {
            ["partner_sync_id":$0.partnerSyncID,"previous_revision":$0.previousRevision,
             "following_revision":$0.followingRevision+1,"natural_revision":1]
        }
        let manifest: [[String:Any]] = request.bill.eventKeys.sorted().map {
            let fields = $0.split(separator:"|",maxSplits:1).map(String.init)
            return ["kind":fields[0],"key":fields[1],"revision":1]
        }
        let original: [String:Any] = ["status":"committed","operation_id":wire.operation_id,
            "book_id":wire.book_id,"record_sync_id":BusinessUploadPolicy.androidSyncID(date:scope.date,storeSyncID:scope.storeID),
            "collector_sync_ids":request.base.prepared.proposal.collectors.map(\.partnerSyncID),"payload_hash":request.hash,
            "sync_cursor":22,"customer_cursor":10,"bill_events":manifest,"overnight_receipts":revisions,
            "expense_payer_sync_id":wire.expense_payer_sync_id ?? ""]
        func decode(_ body:[String:Any]) throws -> TXBillV3Receipt {
            try JSONDecoder().decode(TXBillV3Receipt.self,from:JSONSerialization.data(withJSONObject:body))
        }
        XCTAssertTrue(try decode(original).matches(request))
        var broken = original; broken["payload_hash"] = request.base.prepared.hash
        XCTAssertFalse(try decode(broken).matches(request))
        broken = original; broken["bill_events"] = Array(manifest.dropLast())
        XCTAssertFalse(try decode(broken).matches(request))
        broken = original; broken["customer_cursor"] = 0
        XCTAssertFalse(try decode(broken).matches(request))
        XCTAssertFalse(try decode(original).verified(request,records:records,events:[],ledgerCursor:22,customerCursor:10))
    }
}
